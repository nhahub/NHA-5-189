import {spawnSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';
const auth=spawnSync('git',['credential','fill'],{input:'protocol=https\nhost=github.com\n\n',encoding:'utf8',env:{...process.env,GIT_TERMINAL_PROMPT:'0',GCM_INTERACTIVE:'never'}});
const line=auth.stdout.split('\n').find(x=>x.startsWith('password='));
if(!line)throw new Error('Stored GitHub credential unavailable');
const headers={Accept:'application/vnd.github+json','X-GitHub-Api-Version':'2022-11-28','User-Agent':'resume-gap-pages-verification',Authorization:`Bearer ${line.slice(9)}`};
const api='https://api.github.com/repos/SadeenTag/depi_gapAnalyzer';
const runs=await fetch(api+'/actions/workflows/pages.yml/runs?per_page=1',{headers}).then(r=>r.json());
const run=runs.workflow_runs[0];
if(run.status!=='completed'||run.conclusion!=='success')throw new Error(`Workflow not yet successful: ${run.status}/${run.conclusion}`);
const jobs=await fetch(api+`/actions/runs/${run.id}/jobs`,{headers}).then(r=>r.json());
const job=jobs.jobs.find(j=>j.name==='verify-live');
if(!job||job.conclusion!=='success')throw new Error('Live verification job not successful');
const response=await fetch(api+`/actions/jobs/${job.id}/logs`,{headers});
if(!response.ok)throw new Error(`Logs unavailable: ${response.status}`);
const log=(await response.text()).split('\n').map(line=>line.replace(/^\d{4}-\d\d-\d\dT\S+\s?/, '')).join('\n');
const start=log.indexOf('{\n  "site_url":');const end=log.indexOf('\n}',start)+2;
if(start<0||end<start)throw new Error('Verification JSON not found in successful job logs');
const result=JSON.parse(log.slice(start,end));
result.workflow={id:run.id,sha:run.head_sha,url:run.html_url,conclusion:run.conclusion,verification_job_id:job.id};
writeFileSync('.deployment-work/live-verification.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
